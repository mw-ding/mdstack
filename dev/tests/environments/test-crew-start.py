"""Tests for mdstack start, the owner's native start-or-reattach command (#1919); fixtures in crew_testlib.py.

One state matrix (docs/specs/portable.md, M59 O1, rows M1-M9) over every entry point: `mdstack start`, its alias
`mdstack up --attach`, the `<home>/start` wrapper `mdstack layout --write` writes now (with and without the redundant
--attach), and a wrapper written before #1919 that runs `mdstack up --attach`. Each row names the effects it checks:
new-session, new-window (role windows), attach-session/switch-client, watcher starts and state writes. Every refusal
shows zero startup effects beside a valid control. Default project resolution, the --team/ROLE refusals, help and
the layout marker rule complete it. Fake tmux and disposable state only: no real session is touched. Run in CI.
"""
import fcntl
import json
import os
import shlex
import shutil
import subprocess
import sys
import time
import unittest
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # dev/tests/: crew_testlib
from crew_testlib import Base, CREW, INPUTS

MARKER = "# Generated by mdstack layout --write (#1178); rerun it after the layout moves."
TARGET = "=crew-acme-widgets:0"
ENTRIES = ("start", "up --attach", "new wrapper", "new wrapper --attach", "old wrapper --attach")
VERB = {"start": "start", "up --attach": "up --attach", "new wrapper": "start", "new wrapper --attach": "start",
        "old wrapper --attach": "up --attach"}


class StartMatrix(Base):
    def setUp(self):
        super().setUp()
        for name in ("CREW_ROLE", "TMUX", "TMUX_PANE"):  # this suite may itself run in a crew pane
            self.env.pop(name, None)
        self.env["TMUX_TMPDIR"] = os.path.join(self.tmp, "tmux-tmp")
        self.socket_dir = os.path.join(self.env["TMUX_TMPDIR"], "tmux-%d" % os.getuid())
        self.wrapper = os.path.join(self.project_dir, "start")
        r = self.crew("layout", "--project", self.project, "--write")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.old_wrapper = os.path.join(self.tmp, "old-start")  # the v7.14.0 form, still on disk at an owner's home
        with open(self.old_wrapper, "w") as f:
            f.write("#!/bin/sh\n%s\nexec %s up --project %s \"$@\"\n" % (MARKER, shlex.quote(CREW),
                                                                        shlex.quote(self.project)))
        os.chmod(self.old_wrapper, 0o755)

    def write_profile(self, runtime="tmux", engine="claude-code"):
        """The base profile with paths.mdstack at this checkout, so a generated wrapper runs this CLI."""
        super().write_profile(runtime, engine)
        with open(self.project, "a") as f:
            f.write("mdstack = %s\n" % json.dumps(os.path.dirname(os.path.dirname(CREW))))

    def reset(self):
        """A stopped crew: no fake tmux server state, no call log, no project state; the profile rewritten."""
        for path in (self.log, self.log + ".sockets", self.state_file):
            if os.path.exists(path):
                os.remove(path)
        shutil.rmtree(os.path.join(self.tmp, "state"), ignore_errors=True)
        self.write_profile()

    def run_entry(self, entry, *extra, leads=False, **env):
        """Run one entry point from /; without leads, the fixture inputs render no lead briefs (faster)."""
        extra = list(extra) + ([] if leads or "--inputs" in extra else ["--inputs", INPUTS])
        argv = {"start": [sys.executable, CREW, "start", "--project", self.project],
                "up --attach": [sys.executable, CREW, "up", "--project", self.project, "--attach"],
                "new wrapper": [self.wrapper], "new wrapper --attach": [self.wrapper, "--attach"],
                "old wrapper --attach": [self.old_wrapper, "--attach"]}[entry]
        return subprocess.run(argv + extra, capture_output=True, text=True, cwd="/", env=dict(self.env, **env))

    def names(self):
        return [c[0] for c in self.calls()]

    def joins(self):
        return [c for c in self.calls() if c[0] in ("attach-session", "switch-client")]

    def assert_no_start(self, r):
        """Zero startup effects: no tmux call beyond a has-session probe, and no project state written."""
        self.assertFalse([c for c in self.calls() if c[0] != "has-session"], (self.calls(), r.stdout + r.stderr))
        self.assertFalse(os.path.exists(self.state), r.stdout + r.stderr)

    def test_m1_stopped_crew_starts_one_session_then_attaches(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                r = self.run_entry(entry, leads=True)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertEqual(self.names().count("new-session"), 1)
                self.assertEqual(self.names().count("new-window"), 3)  # the three enabled pool leads
                self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]])  # no -r: interactive
                self.assertLess(self.names().index("new-session"), self.names().index("attach-session"))
                self.assertEqual(self.names()[-1], "attach-session")  # after the role windows, last

    def test_m1_failed_start_attaches_nothing(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                with open(self.project, "a") as f:
                    f.write('\n[runtime.options.notes]\ncoordinator = ["policy.md"]\n')
                r = self.run_entry(entry)
                self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
                self.assertIn("cannot read runtime.options.notes.coordinator file policy.md", r.stdout)
                self.assertNotIn("new-session", self.names())
                self.assertEqual(self.joins(), [])

    def test_m1_m2_one_watcher_and_none_on_reattach(self):
        self.env["CREW_WATCHER"] = ""  # a live watcher; the fixture inputs start no leads to race the fake tmux
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                r = self.run_entry(entry, "--inputs", INPUTS)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                started = [x for x in r.stdout.splitlines() if x.startswith("crew: persistent watcher started")]
                self.assertEqual(len(started), 1, r.stdout)
                self.stop_watcher(int(started[0].split("pid ")[1].split(",")[0]))
                r = self.run_entry(entry, "--inputs", INPUTS)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertNotIn("persistent watcher", r.stdout)
                self.assertEqual(self.names().count("new-session"), 1)
                self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]] * 2)

    def stop_watcher(self, pid):
        """SIGTERM the watcher and wait until it frees wake/watcher.lock, held for its whole life (#1654)."""
        subprocess.run(["kill", str(pid)], capture_output=True)
        deadline = time.monotonic() + 20
        with open(os.path.join(self.state, "wake", "watcher.lock"), "a") as f:
            while True:
                try:
                    fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    return
                except BlockingIOError:
                    self.assertLess(time.monotonic(), deadline, "watcher %d still holds its lock" % pid)
                    time.sleep(0.05)

    def test_m2_running_crew_attaches_with_no_second_session(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                self.assertEqual(self.crew("up", "--project", self.project).returncode, 0)
                for _ in range(2):
                    r = self.run_entry(entry, leads=True)
                    self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                    self.assertIn("crew-acme-widgets already running", r.stdout)
                self.assertEqual(self.names().count("new-session"), 1)  # from the plain up
                self.assertEqual(self.names().count("new-window"), 3)  # live leads are not started again
                self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]] * 2)

    def test_m2_running_crew_attaches_even_when_the_role_pass_fails(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                self.assertEqual(self.crew("up", "--project", self.project).returncode, 0)
                with open(self.state_file) as f:
                    tmux = json.load(f)
                tmux["crew-acme-widgets"]["2"] = "intruder"  # ben-lead's window index taken by another window
                with open(self.state_file, "w") as f:
                    json.dump(tmux, f)
                r = self.run_entry(entry, leads=True)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertIn("crew: lead window 2 occupied", r.stdout)
                self.assertEqual(self.names().count("new-session"), 1)
                self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]])

    def test_m3_same_server_client_switches_instead_of_nesting(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                r = self.run_entry(entry, TMUX="%s,4242,3" % os.path.join(self.socket_dir, "default"))
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertEqual(self.names().count("new-session"), 1)
                self.assertEqual(self.joins(), [["switch-client", "-t", TARGET]])

    def test_m4_foreign_server_client_refuses_before_any_start(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                r = self.run_entry(entry, TMUX="%s,4242,3" % os.path.join(self.socket_dir, "crew-acme-widgets"))
                self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
                self.assertIn("crew: refusing %s: this tmux client is on another server" % VERB[entry], r.stdout)
                self.assertIn("detach and retry", r.stdout)
                self.assert_no_start(r)
                r = self.run_entry(entry, TMUX="%s,4242,3" % os.path.join(self.socket_dir, "default"))  # control
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertEqual(self.joins(), [["switch-client", "-t", TARGET]])

    def test_m5_crew_pane_refuses_before_any_tmux_call_or_write(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                with open(self.wrapper) as f:
                    wrapper = f.read()
                r = self.run_entry(entry, CREW_ROLE="builder", TMUX="%s,4242,3" % os.path.join(self.socket_dir, "default"))
                self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
                self.assertEqual(r.stdout, "crew: refusing %s: run from a crew pane (CREW_ROLE=builder); it is the "
                                           "owner's terminal shortcut\n" % VERB[entry])
                self.assertEqual(self.calls(), [])
                self.assertFalse(os.path.exists(self.state))
                with open(self.wrapper) as f:
                    self.assertEqual(f.read(), wrapper)
                r = self.run_entry(entry)  # control
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]])

    def test_m6_missing_invalid_or_ambiguous_profile_refuses_before_any_start(self):
        team = ('[team]\nname = "acme"\n[repos.widgets]\nrepo = "acme/widgets"\n'
                '[repos.gadgets]\nrepo = "acme/gadgets"\n')
        cases = {"missing": (None, "cannot read (No such file or directory)"),
                 "invalid": ("[repo\n", "invalid TOML"),
                 "ambiguous": (team, "lists 2 repos; select one as %s#<repo>" % self.project)}
        for entry in ENTRIES:
            for case, (text, reason) in cases.items():
                with self.subTest(entry=entry, case=case):
                    self.reset()
                    os.remove(self.project)
                    if text is not None:
                        with open(self.project, "w") as f:
                            f.write(text)
                    r = self.run_entry(entry)
                    self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
                    self.assertEqual(r.stderr, "mdstack: config %s\n" % self.project)
                    self.assertEqual(len(r.stdout.splitlines()), 1, r.stdout)
                    self.assertIn(reason, r.stdout)
                    self.assertEqual(self.calls(), [])
                    self.assertFalse(os.path.exists(os.path.join(self.tmp, "state")))
                    self.write_profile()  # control
                    r = self.run_entry(entry)
                    self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                    self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]])

    def test_m6_team_or_role_refuses_with_one_line(self):
        for argv, refused in ((["start", "--team", self.project], "--team"),
                              (["start", "builder", "--project", self.project], "a ROLE"),
                              ([self.wrapper, "builder"], "a ROLE")):
            with self.subTest(argv=argv):
                self.reset()
                cmd = argv if argv[0] == self.wrapper else [sys.executable, CREW, *argv]
                r = subprocess.run(cmd, capture_output=True, text=True, cwd="/", env=self.env)
                self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
                self.assertEqual(r.stdout, "crew: refusing start: it takes --project, not %s\n" % refused)
                self.assertEqual(self.calls(), [])
                self.assertFalse(os.path.exists(self.state))

    def test_default_project_resolution_from_any_directory(self):
        missing = os.path.join(self.tmp, "nowhere", "config.toml")
        for env, config in (({"MDSTACK_CONFIG": self.project}, self.project),
                            ({"CREW_PROJECT": self.project, "MDSTACK_CONFIG": missing}, self.project),
                            ({"CREW_ROOT": os.path.dirname(missing)}, missing)):
            with self.subTest(env=sorted(env)):
                self.reset()
                r = subprocess.run([sys.executable, CREW, "start", "--inputs", INPUTS], capture_output=True, text=True, cwd="/",
                                   env=dict(self.env, **env))
                self.assertEqual(r.stderr, "mdstack: config %s\n" % config)
                if config == missing:  # no profile: one line, before anything starts
                    self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
                    self.assertEqual(r.stdout, "%s:(file): cannot read (No such file or directory)\n" % missing)
                    self.assertEqual(self.calls(), [])
                    self.assertFalse(os.path.exists(os.path.join(self.tmp, "state")))
                else:
                    self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                    self.assertEqual(self.names().count("new-session"), 1)
                    self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]])

    def test_m7_paused_project_starts_window_zero_only_then_attaches(self):
        for entry in ENTRIES:
            with self.subTest(entry=entry):
                self.reset()
                self.put("pause.json", json.dumps({"by": "owner", "at": "2026-11-15T00:00:00Z"}))
                r = self.run_entry(entry, leads=True)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertIn("crew: project paused; started no role windows (mdstack resume)", r.stdout)
                self.assertEqual(self.names().count("new-session"), 1)
                self.assertNotIn("new-window", self.names())
                self.assertEqual(self.joins(), [["attach-session", "-t", TARGET]])

    def test_m8_plain_up_and_the_old_wrapper_without_attach_never_attach(self):
        for argv in ([sys.executable, CREW, "up", "--project", self.project], [self.old_wrapper]):
            with self.subTest(argv=argv[-1]):
                self.reset()
                r = subprocess.run(argv, capture_output=True, text=True, cwd="/", env=self.env)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assertEqual(self.names().count("new-session"), 1)
                self.assertEqual(self.joins(), [])

    def test_m8_new_wrapper_runs_start(self):
        with open(self.wrapper) as f:
            self.assertEqual(f.read().splitlines()[1:], [
                MARKER, "exec %s start --project %s \"$@\"" % (shlex.quote(CREW), shlex.quote(self.project))])

    def test_m9_layout_write_refuses_an_unowned_start_and_rewrites_its_own(self):
        shutil.copy(self.old_wrapper, self.wrapper)  # control: an old generated wrapper is rewritten to start
        r = self.crew("layout", "--project", self.project, "--write")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        with open(self.wrapper) as f:
            self.assertIn(" start --project ", f.read())
        with open(self.wrapper, "w") as f:
            f.write("#!/bin/sh\necho mine\n")
        r = self.crew("layout", "--project", self.project, "--write")
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn("crew: refusing layout --write: not generated by crew layout: " + self.wrapper, r.stdout)
        with open(self.wrapper) as f:
            self.assertEqual(f.read(), "#!/bin/sh\necho mine\n")

    def test_help_lists_start_as_the_shortcut(self):
        r = self.crew("--help")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn(",start,", r.stdout)
        self.assertIn("mdstack start                (the owner's shortcut", r.stdout)
        r = self.crew("start", "--help")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("exactly `mdstack up --attach`", r.stdout)
        self.assertIn("window 0", r.stdout)


if __name__ == "__main__":
    unittest.main()
